"""Backfill the archive's windGust10 column from InfluxDB (DEC-0232).

The archive gained a `windGust10` column (the ISS's own 10-minute gust, message 9) long after
InfluxDB started storing the same value as `windGust10_mph` (2026-10-28 12:30 ET, DEC-0224).
Both come from the same in-memory archive record (WeeWX's stock `last` extractor), so the
InfluxDB value is the value the archive would have stored. This script copies it.

It never writes to a database itself. It reads InfluxDB through a read-only Flux endpoint and
writes a SQL file. The SQL sets only cells that are still NULL, at rows that already exist,
inside one transaction; it inserts no row and overwrites no value. Apply it with the sqlite3
shell as the archive's owning user; docs/WINDGUST10-MIGRATION.md has the exact steps.

    python3 ops/backfill_windgust10.py --query-url <flux /query URL> --out gust10.sql
    python3 ops/backfill_windgust10.py --csv saved.csv --out gust10.sql

The query URL takes a raw Flux body (Content-Type application/vnd.flux) and answers CSV, as
the dashboard's read-only proxy does. Values are mph, the unit of a US archive, so each UPDATE
also requires `usUnits = 1` and sets nothing in an archive stored in other units. Without the
column the first UPDATE fails, `.bail on` stops the shell, and the open transaction is dropped.
"""
import argparse
import csv
import datetime
import io
import math
import sys
import urllib.request

FIELD = 'windGust10_mph'
# The first archive record that carried windGust10, 2026-10-28 16:30:00 UTC (DEC-0224).
DEFAULT_START = '2026-10-28T16:00:00Z'
# The driver's bounds for the gust are 0..89.4 m/s, 200 mph (DEC-0224).
MAX_MPH = 200.0
FLUX = '''from(bucket: "%(bucket)s")
  |> range(start: %(start)s, stop: %(stop)s)
  |> filter(fn: (r) => r._measurement == "record" and r.binding == "archive" and r._field == "%(field)s")
  |> keep(columns: ["_time", "_value"])
'''


def flux_query(bucket, start, stop):
    return FLUX % {'bucket': bucket, 'start': start, 'stop': stop, 'field': FIELD}


def fetch_csv(url, flux, timeout=60):
    req = urllib.request.Request(url, data=flux.encode('utf-8'), method='POST', headers={
        'Content-Type': 'application/vnd.flux', 'Accept': 'application/csv'})
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return resp.read().decode('utf-8')


def _epoch(rfc3339):
    t = datetime.datetime.fromisoformat(rfc3339.replace('Z', '+00:00'))
    if t.tzinfo is None:
        raise ValueError('timestamp without a zone: %r' % rfc3339)
    return int(t.timestamp())


def parse_points(text):
    """Return sorted [(epoch, mph)] from Flux CSV. A row that is not a clean point is an error,
    not a skip: a silent skip would leave a NULL that looks like a minute without message 9."""
    points = {}
    header = None
    for row in csv.reader(io.StringIO(text)):
        if not row or not any(cell.strip() for cell in row):
            header = None  # a blank line ends a result table; the next row is a header
            continue
        if row[0].startswith('#'):
            continue  # an annotation row
        if header is None:
            header = row
            if '_time' not in header or '_value' not in header:
                raise ValueError('no _time/_value columns in the CSV header: %r' % row)
            continue
        cells = dict(zip(header, row))
        if cells.get('_time') == '_time':
            continue  # a repeated header between result tables
        epoch = _epoch(cells['_time'])
        mph = float(cells['_value'])
        if not math.isfinite(mph) or not 0.0 <= mph <= MAX_MPH:
            raise ValueError('implausible gust %r at %s' % (cells['_value'], cells['_time']))
        if epoch in points and points[epoch] != mph:
            raise ValueError('two values at %s' % cells['_time'])
        points[epoch] = mph
    return sorted(points.items())


def build_sql(points, source):
    lines = [
        '-- windGust10 backfill from InfluxDB %s (DEC-0232), generated by ops/backfill_windgust10.py' % FIELD,
        '-- source: %s' % source,
        '-- %d points; values are mph, for a US archive (usUnits = 1) only.' % len(points),
        '-- Sets only NULL cells at existing rows; inserts nothing, overwrites nothing.',
        '.bail on',
        '.timeout 30000',
        'BEGIN;',
    ]
    for epoch, mph in points:
        lines.append('UPDATE archive SET windGust10 = %r WHERE dateTime = %d '
                     'AND windGust10 IS NULL AND usUnits = 1;' % (mph, epoch))
    lines += [
        'SELECT \'cells set: \' || total_changes();',
        'COMMIT;',
        'SELECT \'rows with windGust10 now: \' || COUNT(windGust10) FROM archive;',
        '',
    ]
    return '\n'.join(lines)


def local_dates(points):
    """First and last local date covered: the range for `weectl database rebuild-daily`
    (which takes local dates, not UTC). Uses this machine's time zone."""
    if not points:
        return None, None
    first = datetime.datetime.fromtimestamp(points[0][0]).date()
    last = datetime.datetime.fromtimestamp(points[-1][0]).date()
    return first, last


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument('--query-url', help='a Flux /query endpoint that answers CSV')
    src.add_argument('--csv', help='a saved Flux CSV answer instead of a live query')
    ap.add_argument('--bucket', default='weewx')
    ap.add_argument('--start', default=DEFAULT_START, help='RFC 3339, default %(default)s')
    ap.add_argument('--stop', default='now()', help='RFC 3339 or now(), default %(default)s')
    ap.add_argument('--out', required=True, help='the SQL file to write')
    args = ap.parse_args(argv)

    if args.csv:
        with open(args.csv, encoding='utf-8') as f:
            text = f.read()
        source = 'csv file %s' % args.csv
    else:
        text = fetch_csv(args.query_url, flux_query(args.bucket, args.start, args.stop))
        source = 'Flux range(start: %s, stop: %s)' % (args.start, args.stop)
    points = parse_points(text)
    if not points:
        print('no %s points: nothing written' % FIELD, file=sys.stderr)
        return 1
    with open(args.out, 'w', encoding='utf-8') as f:
        f.write(build_sql(points, source))
    first, last = local_dates(points)
    print('%d points, %s to %s UTC -> %s' % (
        len(points),
        datetime.datetime.fromtimestamp(points[0][0], datetime.timezone.utc).isoformat(),
        datetime.datetime.fromtimestamp(points[-1][0], datetime.timezone.utc).isoformat(),
        args.out))
    print('local dates covered: %s to %s (rebuild-daily range; leave today to weewxd)'
          % (first, last))
    return 0


if __name__ == '__main__':
    sys.exit(main())
